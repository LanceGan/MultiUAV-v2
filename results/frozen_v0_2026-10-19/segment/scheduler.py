"""Sector association + shared bandwidth scheduler (new design §7).

Given the ALNS routes, this simulates the multi-UAV flight with per-step sector
association (best-SINR sector) and shared bandwidth (UAVs in the same sector
split that sector's bandwidth equally), and recomputes the upload delay.

v1 approximation: trajectories are FIXED (generated by the single-segment TD3 at
full bandwidth B=1); the scheduler only re-evaluates the upload rate under
sharing, so a UAV that shares a sector uploads slower and its delay scales by the
average number of co-sector UAVs along its path.
"""

import argparse
import json
import math
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from experiment.run_traj import fixed_traverse
from radio_map import radio_map_A2G
from segment.env import UAV_H, CommField, SingleSegmentEnv
from segment.td3 import TD3

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODEL_DIR = os.path.join(ROOT, "results", "models", "segment")

SIR_THRESHOLD = 3.0  # must match radio_map_A2G.SIR_THRESHOLD


def per_sector_sinr(pos):
    """Per-BS per-sector average SINR (dB), shape (numBS, Sec_num)."""
    loc = np.array([pos[0] / 10.0, pos[1] / 10.0, UAV_H / 10.0])
    _, sinr = radio_map_A2G.getPointOutageMatrix(loc, SIR_THRESHOLD)
    return np.asarray(sinr, dtype=float)


def best_sector(pos):
    """Return the flat sector id (0 .. numBS*Sec_num-1) with the best SINR."""
    sinr = per_sector_sinr(pos)
    idx = int(np.argmax(sinr))
    return idx


def rollout_route(cfg, route, points, data_sizes, model, field):
    """Roll out one UAV's full route -> (positions (N,2), base_delay per step)."""
    ini = np.asarray(cfg["ini_loc"], float)
    end = np.asarray(cfg["end_loc"], float)
    route = [int(j) for j in route]
    wps = [ini] + [np.asarray(points[j], float) for j in route] + [end]
    datas = [0.0] + [float(data_sizes[j]) for j in route]

    mi = np.zeros(2, np.float32)
    ma = np.array([float(cfg["v_max"]), 2.0 * math.pi], np.float32)

    positions = []
    for r in range(len(wps) - 1):
        e = SingleSegmentEnv(cfg, wps[r], wps[r + 1], datas[r], field=field)
        e.reset()
        while True:
            a = np.clip(model.select_action(e._state()), mi, ma)
            s_, rr, done, info = e.step(a)
            positions.append(e.pos.copy())
            if done:
                break
    return np.asarray(positions)


def congestion_factors(cfg, routes, points, data_sizes, model, field):
    """Per-UAV average co-sector UAV count (>= 1).  factor=1 means never shared."""
    trajs = [rollout_route(cfg, r, points, data_sizes, model, field) for r in routes]
    n_uav = len(routes)
    factors = []
    for u in range(n_uav):
        shared = []
        for t in range(len(trajs[u])):
            sec_u = best_sector(trajs[u][t])
            cnt = 1
            for v in range(n_uav):
                if v == u or t >= len(trajs[v]):
                    continue
                if best_sector(trajs[v][t]) == sec_u:
                    cnt += 1
            shared.append(cnt)
        factors.append(float(np.mean(shared)))
    return factors


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--uav_num", type=int, default=2)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args(argv)

    cfg, points, data_sizes, _ = fixed_traverse(args.uav_num, args.seed)
    with open(os.path.join(MODEL_DIR, "alns_routes_uav%d.json" % args.uav_num)) as f:
        routes = json.load(f)

    field = CommField(cfg, spacing=0.25)
    ma = np.array([float(cfg["v_max"]), 2.0 * math.pi], np.float32)
    mi = np.zeros(2, np.float32)
    model = TD3(6, 2, ma, mi)
    model.load(os.path.join(MODEL_DIR, "uav2_allpairs.pth"))

    factors = congestion_factors(cfg, routes, points, data_sizes, model, field)
    print("per-UAV average co-sector UAV count (shared-bandwidth factor):")
    for u, f in enumerate(factors):
        print("  UAV %d: %.2f" % (u, f))

    # Base (non-shared) delay from the edge weights.
    from segment.alns import load_weights, ALNS
    flight, delay, outage, feas = load_weights(
        os.path.join(MODEL_DIR, "edge_weights_uav%d.npz" % args.uav_num))
    base_D = 0.0
    shared_D = 0.0
    K = len(points)
    for u, route in enumerate(routes):
        route = [int(j) for j in route]
        d = delay[0, route[0]] + delay[route[-1] + 1, K]
        for r in range(len(route) - 1):
            d += delay[route[r] + 1, route[r + 1]]
        base_D += d
        shared_D += d * factors[u]
    print("total delay: base (B=1, no sharing) = %.1f s" % base_D)
    print("total delay: shared-bandwidth (v1)  = %.1f s" % shared_D)
    print("sharing inflation: +%.1f%%" % (100.0 * (shared_D / base_D - 1.0)))
    return 0


if __name__ == "__main__":
    main()
